export const DEFAULT_PERSONA_ID = "mesatlebet";

export function getPersona(id: string | null | undefined): BotPersona {
  return BOT_PERSONAS.find((p) => p.id === id) ?? BOT_PERSONAS[0];
}

// בלוק ההנחיה שנוסף ל-system prompt לפי הסגנון שנבחר.
export function personaSystemBlock(id: string | null | undefined): string {
  const p = getPersona(id);
  return `\n---\n## סגנון הדיבור שהמשתמש בחר (גובר על כל הנחיית סגנון קודמת)\n${p.prompt}\n(אל תשנה את פורמט הסיום "הצעות המשך:", את קישורי המרקדאון לאפליקציות, את השימוש בכלים, את כללי הברזל או את הגבולות — רק את אופי הדיבור.)`;
}
